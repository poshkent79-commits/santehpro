/**
 * Извлекает базовые технические параметры из base64-строки изображения
 */
export function inspectImageBuffer(base64Data: string): PhotoInspectionData {
  try {
    const cleanBase64 = base64Data.replace(/^data:image\/\w+;base64,/, '');
    const buffer = Buffer.from(cleanBase64, 'base64');
    const sizeKb = Math.round(buffer.length / 1024);

    let format: PhotoInspectionData['format'] = 'unknown';
    let width: number | undefined;
    let height: number | undefined;

    // Определение формата по magic bytes
    if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
      format = 'jpeg';
      // Поиск маркера SOF0 (0xFFC0) или SOF2 (0xFFC2) в JPEG
      let offset = 2;
      while (offset < buffer.length - 8) {
        if (buffer[offset] === 0xff) {
          const marker = buffer[offset + 1];
          if (marker === 0xc0 || marker === 0xc2) {
            height = buffer.readUInt16BE(offset + 5);
            width = buffer.readUInt16BE(offset + 7);
            break;
          } else if (marker === 0xd9 || marker === 0xda) {
            break; // Конец заголовков
          } else {
            const len = buffer.readUInt16BE(offset + 2);
            offset += 2 + len;
            continue;
          }
        }
        offset++;
      }
    } else if (
      buffer[0] === 0x89 &&
      buffer[1] === 0x50 &&
      buffer[2] === 0x4e &&
      buffer[3] === 0x47
    ) {
      format = 'png';
      if (buffer.length >= 24) {
        width = buffer.readUInt32BE(16);
        height = buffer.readUInt32BE(20);
      }
    } else if (
      buffer[0] === 0x52 &&
      buffer[1] === 0x49 &&
      buffer[2] === 0x46 &&
      buffer[3] === 0x46
    ) {
      format = 'webp';
    }

    let aspectRatio: string | undefined;
    if (width && height) {
      const ratio = width / height;
      if (Math.abs(ratio - 1) < 0.1) aspectRatio = '1:1 (Квадрат)';
      else if (Math.abs(ratio - 1.33) < 0.15) aspectRatio = '4:3 (Стандарт)';
      else if (Math.abs(ratio - 1.77) < 0.15) aspectRatio = '16:9 (Широкоформатный)';
      else if (ratio < 0.8) aspectRatio = 'Вертикальный снимок смартфона';
      else aspectRatio = `${width}x${height} px`;
    }

    return {
      format,
      width,
      height,
      aspectRatio,
      sizeKb,
    };
  } catch (err) {
    return {
      format: 'unknown',
      sizeKb: 0,
    };
  }
}


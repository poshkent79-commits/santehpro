/**
 * Инженерная экспертная база знаний по сантехнике и ИИ-диагностике поломок.
 * Обеспечивает мгновенный двухэтапный анализ строго в рамках поставленного запроса:
 * Этап 1: Первичная диагностика, выявление причин и принципиальное решение проблемы.
 * Этап 2: Пошаговый план работ («Что нужно сделать и какие инструменты нужны?»),
 *         список инструмента, материалов с диаметрами, техника безопасности и совет эксперта.
 */

import {
  analyzePlumbingPhoto,
  formatPhotoInitialDiagnosis,
  formatPhotoActionPlan,
} from './photoAnalyzer';

export interface DiagnosticResult {
  title: string;
  category: string;
  diagnosis: string;
  generalSolution: string;
  tools: string[];
  materials: string[];
  safety: string;
  steps: string[];
  expertTip: string;
}

export interface DiagnosticOptions {
  hasImage?: boolean;
  base64Image?: string;
  imageMimeType?: string;
  visualTag?: string;
  history?: Array<{ role: string; content: string }>;
  forceMode?: 'initial' | 'action' | 'full';
}

export function isActionPlanQuery(query: string): boolean {
  const q = query.toLowerCase().trim();
  return (
    q.includes('что нужно сделать') ||
    q.includes('какие инструмент') ||
    q.includes('какой инструмент') ||
    q.includes('что делать') ||
    q.includes('что надо сделать') ||
    q.includes('какие материалы нужны') ||
    q.includes('инструменты нужны') ||
    q.includes('пошаговый план') ||
    q.includes('пошаговый регламент') ||
    q.includes('инструкция по ремонту') ||
    q.includes('список инструмент') ||
    (q.includes('как починить') && (q.includes('инструмент') || q.includes('детал') || q.includes('шаг')))
  );
}

export function formatInitialDiagnosis(res: DiagnosticResult): string {
  return `### 🔍 ${res.title}
**Категория:** ${res.category}

**Диагностика:** ${res.diagnosis}

💡 **Решение:** ${res.generalSolution}

---
👉 *Чтобы узнать список инструментов и пошаговый план работ, спросите:* **«Что нужно сделать и какие инструменты нужны?»**`;
}

export function formatActionPlan(res: DiagnosticResult): string {
  return `### 🛠 План работ и необходимые инструменты: ${res.title}
**Категория:** ${res.category}

#### 🛠 Необходимый инструмент:
${res.tools.map((t) => `• ${t}`).join('\n')}

#### 📦 Материалы и запчасти:
${res.materials.map((m) => `• ${m}`).join('\n')}

⚠️ **Техника безопасности:** ${res.safety}

#### 📋 Пошаговые действия:
${res.steps.map((s, idx) => `**Шаг ${idx + 1}:** ${s}`).join('\n\n')}

💡 **Совет мастера:** *${res.expertTip}*`;
}

export function formatFullReport(res: DiagnosticResult): string {
  return `### 🔍 ${res.title}
**Категория:** ${res.category}

**Диагностика:** ${res.diagnosis}

💡 **Решение:** ${res.generalSolution}

#### 🛠 Инструмент:
${res.tools.map((t) => `• ${t}`).join('\n')}

#### 📦 Материалы:
${res.materials.map((m) => `• ${m}`).join('\n')}

⚠️ **Техника безопасности:** ${res.safety}

#### 📋 Порядок действий:
${res.steps.map((s, idx) => `**Шаг ${idx + 1}:** ${s}`).join('\n\n')}

💡 **Совет мастера:** *${res.expertTip}*`;
}

/**
 * Извлекает предыдущую тему диалога из истории, если текущий запрос — это запрос инструментов (Этап 2)
 */
function resolveTopicFromHistory(history?: Array<{ role: string; content: string }>): string {
  if (!history || !Array.isArray(history) || history.length === 0) return '';
  for (let i = history.length - 1; i >= 0; i--) {
    const msg = history[i];
    if (msg.role === 'assistant' && msg.content) {
      return msg.content.toLowerCase();
    }
  }
  return '';
}


export type PartCategory =
  | 'heaters_ten'       // ТЭНы (трубчатые электронагреватели)
  | 'anodes'            // Магниевые аноды
  | 'thermostats'       // Термостаты, термозащита, датчики
  | 'gaskets'           // Уплотнительные прокладки и фланцы
  | 'valves_safety'     // Предохранительные клапаны и арматура
  | 'cartridges_mixer'  // Картриджи смесителей и кран-буксы
  | 'installation_cist' // Арматура инсталляций и бачков унитаза
  | 'reducers_filters'  // Редукторы давления, манометры, фильтры
  | 'dielectric_hoses'; // Диэлектрики, гибкая подводка гигант, манжеты

export interface SparePartItem {
  id: string;
  name: string;
  category: PartCategory;
  categoryLabel: string;
  articleNumber: string;
  brandCompatibility: string[]; // e.g. ['Thermex', 'Garanterm']
  fittingType: string;          // e.g. 'Фланец 64 мм', 'Овальный 48x26 мм', 'Резьба 1 1/4"'
  powerWatts?: number;          // e.g. 1500, 2000
  dimensions: string;           // e.g. 'Ø 64 мм, трубка датчика 8 мм, резьба М6'
  description: string;
  keySpecs: string[];
  inStockTypical: boolean;
  unit: string;
}

export interface BoilerBrandPreset {
  id: string;
  brand: string;
  country: string;
  popularSeries: string[];
  flangeType: string;
  tenType: string;
  anodeThread: string;
  gasketType: string;
  features: string;
}

export interface RepairSymptomGuide {
  id: string;
  targetType: 'boiler' | 'plumbing';
  symptom: string;
  shortDescription: string;
  probableCauses: string[];
  diagnosticCheckSteps: string[];
  repairAlgorithm: string[];
  recommendedParts: string[]; // references spare part IDs or names
  requiredTools: string[];
  safetyWarning?: string;
  urgency: 'critical' | 'high' | 'medium';
}

